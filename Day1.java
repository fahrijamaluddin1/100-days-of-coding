// Hari 1: Struktur Dasar Kode Java & Jenis Komentar

/**
 * Class Day1
 * Latihan hari pertama - memahami struktur dasar program Java
 * dan cara menggunakan komentar (single-line, multi-line, javadoc)
 */
public class Day1 {//mendeklarasikan class bernama Day1, sesuai nama file Day1.java.

    public static void main(String[] args) {//method utama, titik awal program dijalankan.

        // Komentar satu baris (single-line comment)
        // Dipakai untuk catatan singkat pada satu baris kode
        System.out.println("Latihan Day 1");//mencetak teks "Latihan Day 1" ke layar.
        /*
         * Komentar banyak baris (multi-line comment)
         * Bisa dipakai untuk menulis catatan
         * yang lebih dari satu baris sekaligus
         */
        System.out.println("Belajar struktur dasar Java");//mencetak teks "Belajar struktur dasar Java" ke layar.

        // Komentar juga bisa diletakkan di akhir baris kode
        System.out.println("Selesai Hari 1"); //mencetak teks "Selesai Hari 1" ke layar.
        // ini contoh komentar di akhir baris
    }//penutup method main.
}//penutup class Day1.
