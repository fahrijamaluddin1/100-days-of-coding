public class Day19 {
    public static void main(String[] args) {
    

        double nilaiDouble = 99.99;
        int nilaiInt = (int) nilaiDouble; 
        System.out.println("double ke int: " + nilaiInt); 

        long nilaiLong = 123456789L;
        int nilaiIntDariLong = (int) nilaiLong; 
        System.out.println("long ke int: " + nilaiIntDariLong);

        int nilaiBesar = 300;
        byte nilaiByte = (byte) nilaiBesar; 
        System.out.println("int ke byte: " + nilaiByte); 

        int kodeAngka = 65;
        char karakter = (char) kodeAngka; 
        System.out.println("int ke char: " + karakter); 
    }
                            }
