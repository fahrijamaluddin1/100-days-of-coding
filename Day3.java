public class Day3 { //Deklarasi class yg namanya Day1
    public static void main(String[] args) {//Method utama, titik awal program dijalankan
        // \n - baris baru
        System.out.println("Baris pertama\nBaris kedua");

        // \t - tab
        System.out.println("Nama:\tBudi Santoso");
        System.out.println("Umur:\t20 tahun");

        // \" - tanda kutip ganda dalam string
        System.out.println("Guru berkata, \"Kerjakan tugas dengan teliti!\"");

        // \' - tanda kutip tunggal dalam string
        System.out.println('a'); // langsung pakai char, hasil: 'a'
        System.out.println("Contoh karakter: \'A\'");

        // \\ - menampilkan backslash
        System.out.println("Lokasi folder: D:\\Tugas\\Java\\Latihan");

        // \r - carriage return (kursor kembali ke awal baris)
        System.out.println("Halo Dunia\rSelamat");
    }//penutup method main
} //penutup class day1
