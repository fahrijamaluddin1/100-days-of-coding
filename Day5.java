public class Day5 {//Deklarasi class yg namanya Day5
    public static void main(String[] args) {//Method main, ini titik awal program dijalankan
        Double IPK = 3.135d;//Membuat variabel bernama IPK, tipe datanya Double dan isi nilai 3.135
        float Lamawaktumakan = 10f;//Membuat variabel bernama Lamawaktumakan, tipe datanya float, diisi nilai 10.
        System.out.printf("Masukkan IPK :%.2f%n", IPK);//mencetak ke layar "masukkan IPK" digabung nilai IPK dengan 2 angka di belakang koma
        System.out.printf("Lama waktu makan :%.2fMenit%n", Lamawaktumakan);//mencetak teks, digabung nilai Lamawaktumakan dengan 2 angka di belakang koma, digabung teks "Menit"
    }//penutup method main
}//penutup class day5.
